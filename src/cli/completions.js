/**
 * @module cli/completions
 *
 * Shell auto-completion for rule-mcp.
 * Generates completion scripts for zsh, bash, and fish.
 *
 * Usage:
 *   rule-mcp completions          → prints zsh completion (auto-detected)
 *   rule-mcp completions --shell zsh
 *   rule-mcp completions --shell bash
 *   rule-mcp completions --shell fish
 *
 * Install:
 *   rule-mcp completions --shell zsh > ~/.zsh/completions/_rule-mcp
 *   rule-mcp completions --shell bash | source   # or add to .bashrc
 *   rule-mcp completions --shell fish > ~/.config/fish/completions/rule-mcp.fish
 */

export function generateCompletions(shell = "zsh") {
  switch (shell) {
    case "bash": {
      return generateBash();
    }
    case "fish": {
      return generateFish();
    }
    case "zsh":
    default: {
      return generateZsh();
    }
  }
}

function generateZsh() {
  return String.raw`#compdef rule-mcp
# zsh completion for rule-mcp
# Generated by rule-mcp completions
# Install: rule-mcp completions --shell zsh > ~/.zsh/completions/_rule-mcp

_pix_galaxy_mcp_commands() {
  local -a commands=(
    'serve:Start MCP server (stdio or SSE)'
    'daemon:Manage background daemon process'
    'install:Install into agent/IDE configuration'
    'uninstall:Remove from agent/IDE configuration'
    'config:Print mcp.json configuration snippet'
    'tools:List or call MCP tools'
    'doctor:Run system health check'
    'skills:Manage skills (reload)'
    'adr:Manage Architecture Decision Records'
    'handoff:Generate LLM context handoff summary'
    'completions:Generate shell completion script'
    'help:Show this help message'
  )
  _describe 'command' commands
}

_pix_galaxy_mcp_options() {
  local -a options=(
    '--help:Show help'
    '-h:Show help'
    '--transport[Transport type]:transport:(stdio sse)'
    '--ssl-cert[TLS certificate path]:file:_files'
    '--ssl-key[TLS private key path]:file:_files'
    '--agent[Agent name]:agent:(claude codex cursor copilot gemini cline roo zed opencode antigravity windsurf kilo kimi vibe grok droid kiro qwen pi vscode jetbrains neovim emacs)'
    '--global:Use global install'
    '--dry-run:Preview without applying'
    '--force:Override existing configuration'
    '--json[JSON arguments for tool call]:json'
    '--status[ADR status]:status:(proposed accepted deprecated superseded)'
    '--context[ADR context string]:string'
    '--decision[ADR decision string]:string'
    '--consequences[ADR consequences string]:string'
    '--tags[ADR tags (comma-separated)]:string'
    '--format[Handoff format]:format:(full brief minimal)'
    '--compress:Compress handoff output'
    '--dir[Project directory]:dir:_files'
    '--telemetry:Include telemetry in doctor report'
    '--shell[Shell type]:shell:(zsh bash fish)'
  )
  _describe 'option' options
}

_pix_galaxy_mcp_daemon_actions() {
  local -a actions=('start:Start daemon' 'stop:Stop daemon' 'status:Check daemon status' 'logs:Show daemon logs')
  _describe 'action' actions
}

_pix_galaxy_mcp_tools_subcommands() {
  local -a sub=('list:List all tools' 'call:Call a tool directly')
  _describe 'subcommand' sub
}

_pix_galaxy_mcp_skills_actions() {
  local -a sub=('reload:Reload skills from disk')
  _describe 'action' sub
}

_pix_galaxy_mcp_adr_actions() {
  local -a sub=('new:Create a new ADR')
  _describe 'action' sub
}

_pix_galaxy_mcp() {
  local curcontext="$curcontext" state line
  typeset -A opt_args

  _arguments -C \
    '--help[Show help]' \
    '-h[Show help]' \
    '1: :->command' \
    '*: :->args'

  case $state in
    command)
      _pix_galaxy_mcp_commands
      ;;
    args)
      case $words[1] in
        daemon)     _pix_galaxy_mcp_daemon_actions ;;
        tools)      _pix_galaxy_mcp_tools_subcommands ;;
        skills)     _pix_galaxy_mcp_skills_actions ;;
        adr)        _pix_galaxy_mcp_adr_actions ;;
        install|uninstall) _pix_galaxy_mcp_options ;;
        handoff|serve|config|doctor|completions|help) _pix_galaxy_mcp_options ;;
        *)          _pix_galaxy_mcp_options ;;
      esac
      ;;
  esac
}

_pix_galaxy_mcp "$@"
`;
}

function generateBash() {
  return `# bash completion for rule-mcp
# Generated by rule-mcp completions
# Source this file or add to ~/.bashrc:
#   source <(rule-mcp completions --shell bash)

_pix_galaxy_mcp() {
  local cur prev words cword
  _init_completion || return

  local commands="serve daemon install uninstall config tools doctor skills adr handoff completions help"
  local daemon_actions="start stop status logs"
  local tools_sub="list call"
  local skills_actions="reload"
  local adr_actions="new"
  local agents="claude codex cursor copilot gemini cline roo zed opencode antigravity windsurf kilo kimi vibe grok droid kiro qwen pi vscode jetbrains neovim emacs"
  local handoff_format="full brief minimal"
  local adr_status="proposed accepted deprecated superseded"
  local shells="zsh bash fish"

  if [[ $cword -eq 1 ]]; then
    COMPREPLY=($(compgen -W "$commands" -- "$cur"))
    return
  fi

  case "\${words[1]}" in
    daemon)
      COMPREPLY=($(compgen -W "$daemon_actions" -- "$cur"))
      ;;
    tools)
      [[ $cword -eq 2 ]] && COMPREPLY=($(compgen -W "$tools_sub" -- "$cur"))
      ;;
    skills)
      [[ $cword -eq 2 ]] && COMPREPLY=($(compgen -W "$skills_actions" -- "$cur"))
      ;;
    adr)
      [[ $cword -eq 2 ]] && COMPREPLY=($(compgen -W "$adr_actions" -- "$cur"))
      [[ $cword -ge 3 ]] && case "\${words[2]}" in
        new) COMPREPLY=($(compgen -W "--status --context --decision --consequences --tags" -- "$cur")) ;;
      esac
      ;;
    install|uninstall)
      COMPREPLY=($(compgen -W "--agent --dry-run --force --global" -- "$cur"))
      [[ $prev == "--agent" ]] && COMPREPLY=($(compgen -W "$agents" -- "$cur"))
      ;;
    serve)
      COMPREPLY=($(compgen -W "--transport --ssl-cert --ssl-key" -- "$cur"))
      [[ $prev == "--transport" ]] && COMPREPLY=($(compgen -W "stdio sse" -- "$cur"))
      ;;
    handoff)
      COMPREPLY=($(compgen -W "--dir --format --compress" -- "$cur"))
      [[ $prev == "--format" ]] && COMPREPLY=($(compgen -W "$handoff_format" -- "$cur"))
      ;;
    completions)
      COMPREPLY=($(compgen -W "--shell" -- "$cur"))
      [[ $prev == "--shell" ]] && COMPREPLY=($(compgen -W "$shells" -- "$cur"))
      ;;
    doctor)
      COMPREPLY=($(compgen -W "--telemetry" -- "$cur"))
      ;;
    *)
      COMPREPLY=($(compgen -W "$commands" -- "$cur"))
      ;;
  esac
}

complete -F _pix_galaxy_mcp rule-mcp
`;
}

