/**
 * @module scripts/reports/census/_docs
 *
 * The nine generated inventories, one per topic.
 *
 * They were fewer, larger files until a reader had to scroll past the
 * guardrail table to reach the prompts, and a diff on any surface touched the
 * same document as every other. One topic per file keeps a change to the tools
 * out of the history of the personas, and lets the handbook link the inventory
 * a chapter is about rather than an anchor inside a long page.
 */

import { commandSection, hookSection } from "./_sections-agent.mjs";
import { cliSection } from "./_sections-cli.mjs";
import { commandKindsSection } from "./_sections-commands.mjs";
import { guardrailSection, personaSection, resourceSection } from "./_sections-quality.mjs";
import { promptSection, skillCatalogSection } from "./_sections-surface.mjs";
import { surfaceMapSection } from "./_sections-surface-map.mjs";
import { actionToolSection, skillToolSection } from "./_sections-tools.mjs";

/** Every generated document, in the order the numbers put them. */
const INDEX = [
  ["09-skills.md", "Skills"],
  ["10-tools.md", "Tools"],
  ["11-prompts.md", "Prompts"],
  ["12-instructions.md", "Instructions"],
  ["13-cli.md", "CLI"],
  ["14-personas.md", "Personas"],
  ["15-guardrails.md", "Guardrails"],
  ["16-resources.md", "Resources"],
  ["17-surface-map.md", "Surface map"],
];

/**
 * The preamble every generated document carries: what it is, and the one
 * command that rewrites it.
 *
 * @param {string} file - the file being built
 * @param {string} title - its heading
 * @returns {string[]}
 */
function header(file, title) {
  return [
    "<!-- Generated by scripts/reports/census/index.mjs. Do not edit by hand. -->",
    "",
    `# ${file.slice(0, 2)} - ${title}`,
    "",
    "Counted from the registries that define it. Run `pnpm census` after changing",
    "a tool, a skill, a prompt, a role, a command or a guardrail;",
    "`tests/docs/census-generated.test.mjs` compares this file against the live",
    "registry, so a stale copy fails the build instead of misleading a reader.",
    "",
  ];
}

/** The other seven, so any one of them is one hop from the rest. */
function footer(file) {
  return ["## The rest of the census", "", ...INDEX.filter(([name]) => name !== file).map(([name, title]) => `- [${name.slice(0, 2)} - ${title}](${name})`), ""];
}

/**
 * One document: its file name, and how its body is built from the gathered
 * surface.
 *
 * @param {string} file
 * @param {string} title
 * @param {(data: object) => string[]} body
 * @returns {{file: string, build: (data: object) => string[]}}
 */
const doc = (file, title, body) => ({
  file,
  build: (data) => [...header(file, title), ...body(data), ...footer(file)],
});

/** Every generated document, with the sections its body is assembled from. */
export const GENERATED_DOCS = [
  doc("09-skills.md", "Skills", (data) => skillCatalogSection(data)),
  doc("10-tools.md", "Tools", (data) => [...actionToolSection(data), ...skillToolSection(data)]),
  doc("11-prompts.md", "Prompts", (data) => promptSection(data)),
  doc("12-instructions.md", "Instructions", (data) => [...commandSection(data), ...commandKindsSection(data), ...hookSection()]),
  doc("13-cli.md", "CLI", () => cliSection()),
  doc("14-personas.md", "Personas", (data) => personaSection(data)),
  doc("15-guardrails.md", "Guardrails", (data) => guardrailSection(data)),
  doc("16-resources.md", "Resources", (data) => resourceSection(data)),
  doc("17-surface-map.md", "Surface map", (data) => surfaceMapSection(data)),
];
